#!/usr/bin/env python3
"""Generate Safari's policy table from the same verified data as Unbound."""

import argparse
import hashlib
import importlib.util
import json

from fetch_confusables import ROOT, SHA256


DESTINATION = ROOT / "safari/extension/confusables.js"


def generated_source():
    data = (ROOT / "files/confusables.txt").read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Unicode data SHA-256 mismatch; run scripts/fetch_confusables.py")
    spec = importlib.util.spec_from_file_location(
        "homograph_filter", ROOT / "files/homograph_filter.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    mappings = module.parse_confusables(data.decode("utf-8").splitlines())
    if len(mappings) != 1407:
        raise ValueError("Unexpected Unicode 17.0.0 mapping count")
    return (
        "// Generated by scripts/build_safari_data.py; do not edit.\n"
        "// Unicode 17.0.0; see NOTICE and LICENSES/Unicode-3.0.txt.\n"
        f"// Source SHA-256: {SHA256}\n"
        "globalThis.AntiHomographMappings = Object.freeze("
        + json.dumps(mappings, ensure_ascii=True, sort_keys=True, indent=2)
        + ");\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    artifacts = {
        DESTINATION: generated_source(),
        DESTINATION.with_name("LICENSE.txt"): (
            ROOT / "LICENSE"
        ).read_text(encoding="utf-8"),
        DESTINATION.with_name("UNICODE-LICENSE.txt"): (
            ROOT / "LICENSES/Unicode-3.0.txt"
        ).read_text(encoding="utf-8"),
    }
    for destination, source in artifacts.items():
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != source:
                parser.error("Safari data/license is stale; run scripts/build_safari_data.py")
        else:
            destination.write_text(source, encoding="utf-8")
    print("Verified Safari policy: Unicode 17.0.0, 1407 mappings")


if __name__ == "__main__":
    main()
